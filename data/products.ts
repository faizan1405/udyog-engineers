/**
 * Related product recommendations adhering to rule 21:
 * Prioritizes:
 * 1. Explicit related products in product.relatedProducts
 * 2. Same subcategory AND same brand/series
 * 3. Same subcategory
 * 4. Same category
 * Demo placeholders are strictly excluded.
 */
export function getRelatedProducts(product: Product, limit: number = 3): Product[] {
  if (product.isDemoPlaceholder) return [];

  const candidates: Product[] = [];

  // 1. Explicit related products defined on the item
  if (product.relatedProducts && product.relatedProducts.length > 0) {
    const explicit = PRODUCTS.filter(
      (p) =>
        !p.isDemoPlaceholder &&
        p.slug.toLowerCase() !== product.slug.toLowerCase() &&
        product.relatedProducts.some(
          (rel) =>
            rel.toLowerCase() === p.slug.toLowerCase() ||
            rel.toLowerCase() === p.id.toLowerCase()
        )
    );
    candidates.push(...explicit);
  }

  // 2. Same subcategory AND same brand
  if (candidates.length < limit && product.subcategorySlug && product.brand) {
    const sameSubcatBrand = PRODUCTS.filter(
      (p) =>
        !p.isDemoPlaceholder &&
        p.slug.toLowerCase() !== product.slug.toLowerCase() &&
        p.subcategorySlug?.toLowerCase() === product.subcategorySlug?.toLowerCase() &&
        p.brand?.toLowerCase() === product.brand?.toLowerCase() &&
        !candidates.some((c) => c.slug.toLowerCase() === p.slug.toLowerCase())
    );
    candidates.push(...sameSubcatBrand);
  }

  // 3. Same subcategory
  if (candidates.length < limit && product.subcategorySlug) {
    const sameSubcat = PRODUCTS.filter(
      (p) =>
        !p.isDemoPlaceholder &&
        p.slug.toLowerCase() !== product.slug.toLowerCase() &&
        p.subcategorySlug?.toLowerCase() === product.subcategorySlug?.toLowerCase() &&
        !candidates.some((c) => c.slug.toLowerCase() === p.slug.toLowerCase())
    );
    candidates.push(...sameSubcat);
  }

  // 4. Same category
  if (candidates.length < limit) {
    const sameCat = PRODUCTS.filter(
      (p) =>
        !p.isDemoPlaceholder &&
        p.slug.toLowerCase() !== product.slug.toLowerCase() &&
        p.categorySlug.toLowerCase() === product.categorySlug.toLowerCase() &&
        !candidates.some((c) => c.slug.toLowerCase() === p.slug.toLowerCase())
    );
    candidates.push(...sameCat);
  }

  return candidates.slice(0, limit);
}

